"""
LoginEvent and SecurityEvent Models (Modules 3 & 4)

Records authentication activity (success/failure, IP, device) and evaluated
security events with calculated risk scores and risk classifications.
"""

from models import db
from models.user import utc_now


class LoginEvent(db.Model):
    """Authentication and session lifecycle event log."""

    __tablename__ = "login_events"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=True, index=True)
    event_type = db.Column(db.String(64), nullable=False)  # LOGIN_SUCCESS, LOGIN_FAILED, LOGOUT, ACCOUNT_LOCKED
    ip_address = db.Column(db.String(64), nullable=True)
    device_info = db.Column(db.String(255), nullable=True)
    timestamp = db.Column(db.DateTime, default=utc_now, nullable=False, index=True)
    success_status = db.Column(db.Boolean, default=False, nullable=False)

    def to_dict(self) -> dict:
        """Serialize login event for activity history and dashboard endpoints."""
        return {
            "id": self.id,
            "user_id": self.user_id,
            "event_type": self.event_type,
            "ip_address": self.ip_address or "Unknown",
            "device_info": self.device_info or "Unknown",
            "timestamp": self.timestamp.isoformat() + "Z",
            "success_status": self.success_status,
        }


class SecurityEvent(db.Model):
    """Evaluated security event generated by the Python risk assessment engine."""

    __tablename__ = "security_events"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False, index=True)
    event_type = db.Column(db.String(64), nullable=False)
    description = db.Column(db.Text, nullable=False)
    risk_score = db.Column(db.Integer, nullable=False, default=0)
    risk_level = db.Column(db.String(16), nullable=False, default="LOW")  # LOW, MEDIUM, HIGH
    # Deduplication key prevents double-counting the exact same underlying event
    source_event_key = db.Column(db.String(128), nullable=True, unique=True)
    # JSON-serialized rule breakdown explaining how the score was calculated
    rule_breakdown = db.Column(db.Text, nullable=True)
    timestamp = db.Column(db.DateTime, default=utc_now, nullable=False, index=True)

    alerts = db.relationship("SecurityAlert", backref="security_event", lazy=True, cascade="all, delete-orphan")

    def to_dict(self) -> dict:
        """Serialize security event including parsed rule breakdown."""
        import json

        breakdown = []
        if self.rule_breakdown:
            try:
                breakdown = json.loads(self.rule_breakdown)
            except ValueError:
                breakdown = []

        return {
            "id": self.id,
            "user_id": self.user_id,
            "event_type": self.event_type,
            "description": self.description,
            "risk_score": self.risk_score,
            "risk_level": self.risk_level,
            "rule_breakdown": breakdown,
            "timestamp": self.timestamp.isoformat() + "Z",
        }
